export const DEFAULT_EMOJI = '🛒';

/**
 * Normaliza o texto removendo acentos e convertendo para minúsculas
 */
function normalizeText(text) {
  return (text || '')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim();
}

/**
 * Tenta detectar o melhor emoji para o nome do item informado
 */
export function detectEmoji(itemName) {
  if (!itemName) return DEFAULT_EMOJI;

  const rawClean = itemName.toLowerCase().trim();
  const normalized = normalizeText(itemName);

  // 1. Verificação exata direta
  if (EMOJI_DICTIONARY[rawClean]) return EMOJI_DICTIONARY[rawClean];
  if (EMOJI_DICTIONARY[normalized]) return EMOJI_DICTIONARY[normalized];

  // 2. Verificação de palavras-chave parciais contidas no nome
  // Priorizar palavras maiores para especificidade (ex: "leite condensado" antes de "leite")
  const keys = Object.keys(EMOJI_DICTIONARY).sort((a, b) => b.length - a.length);

  for (const key of keys) {
    const normKey = normalizeText(key);
    // Testa se a chave existe como palavra inteira ou substring
    const regex = new RegExp(`\\b${normKey}\\b`, 'i');
    if (regex.test(normalized) || normalized.includes(normKey)) {
      return EMOJI_DICTIONARY[key];
    }
  }

  return DEFAULT_EMOJI;
}
